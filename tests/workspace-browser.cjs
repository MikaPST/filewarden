/* Real WordPress workspace acceptance, run by viewer-browser.cjs on disposable fixtures. */
const assert = require('node:assert/strict');
const fs = require('node:fs');
module.exports = async ({ page, context, base, fixture, name }) => {
    await page.setViewportSize({ width: 1600, height: 1000 });
    const workspaceURL = base + '/wp-admin/admin.php?page=filewarden&folder_id=' + fixture.policy_folder;
    await page.goto(workspaceURL);
    const inspector = page.locator('.fw-inspector');
    const openFolderRights = async () => {
        await page.locator('.fw-folder-heading').getByRole('link', { name: 'Edit access rules' }).click();
        await inspector.locator('#inspector-policy').waitFor();
    };
    const openAction = async (filename, label) => {
        const row = page.locator('tbody tr').filter({ hasText: filename });
        await row.locator('.fw-context summary').click();
        await row.locator('.fw-context-menu').getByRole('link', { name: label, exact: true }).click();
        await inspector.waitFor();
    };
    await openFolderRights();
    await inspector.locator('[name="policy_type"]').selectOption('authenticated');
    await inspector.getByRole('button', { name: 'Save access rules' }).click();
    await page.waitForURL(/result=policy_saved/);
    assert.ok((await page.locator('.notice-success').textContent()).includes('Access rules saved'));
    const publicRow = page.locator('tbody tr').filter({ hasText: 'policy-public.pdf' });
    assert.ok((await publicRow.textContent()).includes('Not public: restricted by its folder.'));
    await openAction('policy-inherit.pdf', 'Edit access rules');
    await page.waitForFunction(() => document.querySelector('.fw-inspector h2') === document.activeElement); 
    await inspector.locator('[name="policy_type"]').selectOption('public');
    assert.ok(await inspector.locator('.fw-public-warning').isVisible());
    await inspector.locator('[name="policy_type"]').selectOption('inherit');
    assert.equal(await inspector.locator('.fw-public-warning').isVisible(), false);
    fs.mkdirSync('build/screenshots', { recursive: true });
    await inspector.locator('[name="policy_type"]').selectOption('public');
    await page.screenshot({ path: 'build/screenshots/workspace-' + name + '.png', fullPage: true });
    await page.keyboard.press('Escape');
    await inspector.waitFor({ state: 'hidden' });
    await openFolderRights();
    await inspector.locator('[name="policy_type"]').selectOption('public');
    await inspector.getByRole('button', { name: 'Save access rules' }).click();
    await page.waitForURL(/result=policy_saved/);
    await openAction('policy-inherit.pdf', 'Edit access rules');
    await inspector.locator('[name="policy_type"]').selectOption('authenticated');
    await inspector.getByRole('button', { name: 'Save access rules' }).click();
    await page.waitForURL(/result=policy_saved/);
    await openAction('policy-inherit.pdf', 'Edit access rules');
    assert.equal(await inspector.locator('[name="policy_type"]').inputValue(), 'authenticated');
    await inspector.locator('[name="policy_type"]').selectOption('inherit');
    await inspector.getByRole('button', { name: 'Save access rules' }).click();
    await page.waitForURL(/result=policy_saved/);
    // Each mutation uses the real form and its nonce, never test-only server hooks.
    await openAction('policy-public.pdf', 'Copy');
    await inspector.locator('#fw-destination').selectOption(String(fixture.policy_folder));
    await inspector.getByRole('button', { name: 'Review destination' }).click();
    await inspector.locator('#fw-transfer-name').fill('workspace-copy-' + name + '.pdf');
    await inspector.getByRole('button', { name: 'Confirm copy' }).click();
    await page.waitForURL(/result=success/);
    const copyName = 'workspace-copy-' + name + '.pdf';
    const permanentURL = await page.getByRole('link', { name: copyName, exact: true }).getAttribute('href');
    await openAction(copyName, 'Move');
    await inspector.locator('#fw-destination').selectOption('0');
    await inspector.getByRole('button', { name: 'Review destination' }).click();
    await inspector.getByRole('button', { name: 'Confirm move' }).click();
    await page.waitForURL(/result=success/);
    assert.equal(new URL(page.url()).searchParams.get('folder_id'), '0');
    assert.equal(await page.getByRole('link', { name: copyName, exact: true }).getAttribute('href'), permanentURL);
    await openAction(copyName, 'Move to trash');
    await inspector.getByRole('button', { name: 'Move to trash' }).click();
    await page.waitForURL(/result=success/);
    assert.equal(await page.getByRole('link', { name: copyName, exact: true }).count(), 0);
    assert.equal((await context.request.get(permanentURL)).status(), 404);
    await page.locator('.fw-tabs').getByRole('link', { name: 'Trash', exact: true }).click();
    await openAction(copyName, 'Restore');
    await inspector.getByRole('button', { name: 'Restore', exact: true }).click();
    await page.waitForURL(/result=success/);
    assert.equal((await context.request.get(permanentURL)).status(), 200);
    await page.locator('.fw-tabs').getByRole('link', { name: 'Add documents', exact: true }).click();
    assert.equal(await page.locator('form[data-filewarden-upload]').count(), 1);
    assert.equal(await page.locator('.filewarden-documents').count(), 0);
    await page.screenshot({ path: 'build/screenshots/workspace-add-' + name + '.png', fullPage: true });
    await page.locator('.fw-tabs').getByRole('link', { name: 'Create folder', exact: true }).click();
    assert.equal(await page.locator('#fw-name').count(), 1);
    assert.equal(await page.locator('form[data-filewarden-upload]').count(), 0);
    await page.setViewportSize({ width: 375, height: 812 });
    await page.goto(workspaceURL);
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
    await page.screenshot({ path: 'build/screenshots/workspace-mobile-' + name + '.png', fullPage: true });
};
